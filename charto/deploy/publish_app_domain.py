#!/usr/bin/env python3
"""Add app.pivotnow.in beside the live Azure hostname, with rollback on failure.

Reuse the running host's routes and user plane. No process restart, source
deployment, firewall change, DNS edit or database migration is performed.
The certificate must already be valid before this vhost can be enabled.
"""
import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import re
import shutil
import subprocess
import time
import urllib.request

DOMAIN = "app.pivotnow.in"
OLD_DOMAIN = "pivot-india.centralindia.cloudapp.azure.com"
SITE = Path("/etc/nginx/sites-available/pivotnow-app")
LINK = Path("/etc/nginx/sites-enabled/pivotnow-app")
MARKER = "# Generated by Pivot publish_app_domain.py; routes copied from the live vhost.\n"


def render(source: str) -> str:
    # On this host each top-level server begins on a new unindented line.
    # Keep the existing first TLS server, not the legacy HTTP redirect block.
    match = re.search(r"(?m)^server \{", source)
    if not match:
        raise ValueError("No live server block found")
    server = re.split(r"(?m)^server \{", source[match.end():], maxsplit=1)[0]
    server = "server {" + server
    if OLD_DOMAIN not in server or "listen 443 ssl" not in server or "proxy_pass http://127.0.0.1:3000" not in server:
        raise ValueError("Unexpected live routing; refusing to create a different app")
    server = server.replace(OLD_DOMAIN, DOMAIN)
    # Certbot's certificate directory need not match the server_name (the
    # clean host retained its validation certificate name during cutover).
    for directive, filename in (("ssl_certificate", "fullchain.pem"), ("ssl_certificate_key", "privkey.pem")):
        server, count = re.subn(rf"(?m)^(\s*){directive}\s+[^;]+;",
                               rf"\1{directive} /etc/letsencrypt/live/{DOMAIN}/{filename};", server)
        if count != 1:
            raise ValueError("Unexpected certificate routing")
    server = re.sub(r"(?m)^\s*add_header Strict-Transport-Security[^;]*;", "", server)
    # nginx locations with their own Cache-Control do not inherit add_header.
    server = re.sub(r"(?m)^(\s*)add_header Cache-Control [^;]*;",
                    r'\g<0>\n\1add_header Strict-Transport-Security "max-age=86400" always;', server)
    # Short initial HSTS policy, without includeSubDomains or preload.
    server = server.replace("server {", 'server {\n    add_header Strict-Transport-Security "max-age=86400" always;', 1)
    legal = ""
    for page in ("terms", "privacy", "about"):
        if re.search(rf"location\s*=\s*/{page}\s*\{{", server):
            raise ValueError("Unexpected existing legal route; inspect before replacing")
        legal += f"    location = /{page} {{ return 302 https://www.pivotnow.in/{page}; }}\n"
    server = server.replace("server {", "server {\n" + legal, 1)
    return MARKER + server.rstrip() + "\n" + f'''server {{
    listen 80;
    server_name {DOMAIN};
    location ^~ /.well-known/acme-challenge/ {{ root /var/www/pivot-acme; }}
    location / {{ return 301 https://{DOMAIN}$request_uri; }}
}}
'''


def curl(path: str, domain: str = DOMAIN) -> tuple[int, str]:
    result = subprocess.run([
        "curl", "--silent", "--show-error", "--max-time", "30",
        "--resolve", f"{domain}:443:127.0.0.1", "--write-out", "\n%{http_code}",
        f"https://{domain}{path}",
    ], check=True, capture_output=True, text=True)
    body, status = result.stdout.rsplit("\n", 1)
    return int(status), body


def probe() -> None:
    for domain in (OLD_DOMAIN, DOMAIN):
        status, body = curl("/health", domain)
        if status != 200 or not json.loads(body).get("ready"):
            raise RuntimeError(f"{domain} failed readiness")
    for path in ("/", "/login", "/chart-app/index.html"):
        status, body = curl(path)
        if status != 200 or "<html" not in body.lower():
            raise RuntimeError(f"App HTML failed: {path}")
    status, body = curl("/auth/me")
    baseline_status, baseline_body = curl("/auth/me", OLD_DOMAIN)
    # Charto answers 200 {user:null} when signed out. Compare the live
    # contract instead of inventing a 401 contract or changing authentication.
    if status != baseline_status or json.loads(body) != json.loads(baseline_body):
        raise RuntimeError("Signed-out auth contract changed")
    status, body = curl("/meta")
    if status != 200 or not isinstance(json.loads(body), dict):
        raise RuntimeError("Data API routing failed")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--probe-only", action="store_true")
    args = parser.parse_args()
    request = urllib.request.Request(
        "http://169.254.169.254/metadata/instance?api-version=2021-02-01",
        headers={"Metadata": "true"},
    )
    if json.load(urllib.request.urlopen(request, timeout=10))["compute"]["name"] != "pivot-clean-stage":
        raise SystemExit("Refusing cutover on another VM")
    if args.probe_only:
        probe()
        print("APP_AND_OLD_HOST_PROBES_PASSED")
        return
    health = json.load(urllib.request.urlopen("http://127.0.0.1:5174/health", timeout=15))
    if not health.get("ready") or not health.get("checks", {}).get("backup", {}).get("fresh"):
        raise SystemExit("Readiness or fresh state backup failed; no traffic change")
    cert = f"/etc/letsencrypt/live/{DOMAIN}/fullchain.pem"
    subprocess.run(["openssl", "x509", "-in", cert, "-noout", "-checkhost", DOMAIN], check=True)
    subprocess.run(["openssl", "x509", "-in", cert, "-noout", "-checkend", "604800"], check=True)
    source = Path("/etc/nginx/sites-available/pivot-clean").read_text()
    candidate = render(source)
    if SITE.exists() and not SITE.read_text().startswith(MARKER):
        raise SystemExit("Unrecognised app vhost; refusing overwrite")
    if LINK.exists() and (not LINK.is_symlink() or LINK.resolve() != SITE):
        raise SystemExit("Unexpected enabled site; refusing overwrite")
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    backup = Path("/root/pivot-domain-cutover") / f"nginx-before-{stamp}"
    backup.mkdir(mode=0o700, parents=True)
    shutil.copytree("/etc/nginx", backup / "nginx", symlinks=True)
    previous = SITE.read_bytes() if SITE.exists() else None
    previously_enabled = LINK.is_symlink()
    try:
        SITE.write_text(candidate)
        if not previously_enabled:
            LINK.symlink_to(SITE)
        subprocess.run(["nginx", "-t"], check=True)
        subprocess.run(["systemctl", "reload", "nginx"], check=True)
        time.sleep(1)  # Allow new workers to accept TLS after the graceful reload.
        probe()
    except Exception:
        if not previously_enabled and LINK.is_symlink():
            LINK.unlink()
        if previous is not None:
            SITE.write_bytes(previous)
        else:
            SITE.unlink(missing_ok=True)
        subprocess.run(["nginx", "-t"], check=True)
        subprocess.run(["systemctl", "reload", "nginx"], check=True)
        raise
    report = {"domain": DOMAIN, "backup": str(backup), "source": "pivot-clean", "state_migrated": False,
              "checks": ["TLS", "readiness", "fresh backup", "old hostname", "HTML", "auth", "data API"]}
    Path("/root/pivot-domain-cutover/published.json").write_text(json.dumps(report, indent=2))
    print(json.dumps(report))


if __name__ == "__main__":
    main()
